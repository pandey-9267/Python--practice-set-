# basics of while loop

count = 1
while count <= 5:
    print("Hello")
    count += 1
print(count)

i = 1
while i <= 5:
    print("Abhishek", i)
    i += 1

# print 1 to 5 

no = 1 
while no <= 5:
    print(no)
    no += 1
print("loop ended")

# print form 5 to 1 

num = 5
while num >= 1:
    print(num)
    num -= 1
print("loop ended")
